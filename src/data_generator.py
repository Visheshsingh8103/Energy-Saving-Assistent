def _calculate_temperature(date_obj: datetime, hour: int) -> float:
    """
    Simulate realistic seasonal and diurnal ambient temperature in Celsius.
    Seasonal variation: sinusoidal across days of year (approx 15C min to 35C peak).
    Diurnal variation: lowest around 5 AM, peaks around 2 PM (14:00).
    """
    day_of_year = date_obj.timetuple().tm_yday
    # Seasonal base (summer around day 172, winter day 355)
    seasonal_temp = 24.0 + 8.0 * math.sin(2 * math.pi * (day_of_year - 80) / 365.0)
    
    # Diurnal wave: minimum at 05:00, maximum at 14:00
    diurnal_wave = 5.0 * math.sin(2 * math.pi * (hour - 8) / 24.0)
    
    # Combine with slight random variance
    return round(float(seasonal_temp + diurnal_wave), 1)


def _simulate_occupancy(
    profile: dict,
    date_obj: datetime,
    hour: int,
    rng: np.random.RandomState
) -> int:
    """Simulate realistic head count based on room schedule and day."""
    is_weekend = date_obj.weekday() >= 5
    start_hr = profile["operating_start"]
    end_hr = profile["operating_end"]
    max_occ = profile["max_occupancy"]

    if is_weekend and not profile["weekend_open"]:
        # Closed completely on weekends except rare janitor/security
        return 1 if rng.rand() < 0.05 else 0

    if hour < start_hr or hour >= end_hr:
        # After operating hours
        if hour in (start_hr - 1, end_hr):
            # Cleaning crew / early arrival
            return rng.randint(0, max(2, int(max_occ * 0.1)))
        return 0

    # Inside operating hours
    # Peak mid-morning (10-12) and mid-afternoon (14-16)
    operating_span = end_hr - start_hr
    progress = (hour - start_hr) / max(1, operating_span)
    bell_curve = math.sin(math.pi * progress) ** 1.5

    # Lunch dip around 12:00 - 13:00
    if hour in (12, 13):
        bell_curve *= 0.6

    occ_ratio = bell_curve * rng.uniform(0.7, 1.0)
    if is_weekend:
        occ_ratio *= profile["weekend_factor"]

    return int(max(0, min(max_occ, round(occ_ratio * max_occ))))


def generate_synthetic_energy_dataset(
    days: int = 180,
    start_date: Optional[datetime] = None,
    seed: int = 42,
    location_ids: Optional[List[str]] = None
) -> pd.DataFrame:
    """
    Generate synthetic hourly electricity consumption records for specified locations.
    
    Parameters:
        days: Number of days to generate (minimum 180 required).
        start_date: Starting datetime. Defaults to 180 days before today.
        seed: Random seed for exact reproducibility.
        location_ids: List of location keys to generate for.
        
    Returns:
        pd.DataFrame labeled clearly as synthetic data.
    """
    if days < 180:
        days = 180

    rng = np.random.RandomState(seed)

    if start_date is None:
        # End at yesterday, 23:00
        end_date = datetime.now().replace(minute=0, second=0, microsecond=0)
        start_date = end_date - timedelta(days=days)

    if location_ids is None:
        location_ids = list(LOCATION_PROFILES.keys())

    all_rows = []
    total_hours = days * 24

    for loc_id in location_ids:
        profile = LOCATION_PROFILES.get(loc_id)
        if not profile:
            continue

        for h in range(total_hours):
            current_dt = start_date + timedelta(hours=h)
            hour = current_dt.hour
            day_of_week = current_dt.weekday()
            month = current_dt.month

            temp = _calculate_temperature(current_dt, hour)
            temp += rng.normal(0, 0.5) # tiny sensor-like fluctuation
            temp = round(float(temp), 1)

            occupancy = _simulate_occupancy(profile, current_dt, hour, rng)

            is_open = (profile["operating_start"] <= hour < profile["operating_end"])
            if day_of_week >= 5 and not profile["weekend_open"]:
                is_open = False

            # Base power
            if is_open:
                base_kwh = profile["base_open_kwh"]
            else:
                base_kwh = profile["base_closed_kwh"]

            # Occupant driven consumption
            occupant_kwh = occupancy * profile["kwh_per_occupant"]

            # Cooling / heating load
            cooling_delta = max(0.0, temp - 22.0)
            cooling_kwh = cooling_delta * profile["cooling_sensitivity"] if is_open else (cooling_delta * profile["cooling_sensitivity"] * 0.2)

            # Natural stochastic noise
            noise = rng.normal(0, 0.05 * (base_kwh + occupant_kwh))

            # Base total
            consumption = base_kwh + occupant_kwh + cooling_kwh + noise

            # Occasional injected realistic anomalies
            is_anomaly = 0
            if rng.rand() < profile["anomaly_probability"]:
                anomaly_type = rng.choice(["left_on_overnight", "equipment_spike", "faulty_sensor"])
                if anomaly_type == "left_on_overnight" and not is_open:
                    # AC or lab machines left on overnight
                    consumption += rng.uniform(2.5, 4.2)
                    is_anomaly = 1
                elif anomaly_type == "equipment_spike" and is_open:
                    # High power surge or heavy computation run
                    consumption *= rng.uniform(1.8, 2.6)
                    is_anomaly = 1

            consumption = max(0.05, round(float(consumption), 3))

            all_rows.append({
                "timestamp": current_dt.strftime("%Y-%m-%d %H:%M:%S"),
                "location_id": loc_id,
                "location_name": profile["name"],
                "hour": hour,
                "day_of_week": day_of_week,
                "month": month,
                "temperature": temp,
                "occupancy": occupancy,
                "consumption_kwh": consumption,
                "is_anomaly_flag": is_anomaly,
                "anomaly_score": 0.0,
                "is_demo_injected": 0,
                "is_synthetic": 1  # Transparent labeling
            })

    df = pd.DataFrame(all_rows)
    return df


def save_sample_dataset_csv(filepath: str, days: int = 180, seed: int = 42) -> str:
    """Generate and save the sample CSV dataset."""
    os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
    df = generate_synthetic_energy_dataset(days=days, seed=seed)
    df.to_csv(filepath, index=False)
    return filepath
